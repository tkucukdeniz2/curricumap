"""CurricuMap classification of the held-out registrar titles.

Systems:
  curricumap_v0.1.0   the ELT taxonomy released with v0.1.0
  curricumap_v0.2.0   the bundled ELT taxonomy, written from the official YOK programme lists
                      only and frozen before it was ever applied to the held-out titles
  curricumap_lookup   no rules: the 158 labelled official entries as exact-title overrides
                      (taxonomies/elt_official_titles_lookup.yaml, generated here), i.e. what
                      the labelled list achieves without any pattern
  curricumap_adapted  v0.2.0 plus the institution-specific additions in
                      taxonomies/elt_yok_2018_iuc_adapted.yaml (if present)
"""
from __future__ import annotations

import time

import yaml

from common import ABSTAIN, DOMAINS, HERE, source_courses, target_courses, write_predictions
from curricumap import load_taxonomy
from curricumap.classify import assign_domain

LOOKUP = HERE / "taxonomies" / "elt_official_titles_lookup.yaml"
SYSTEMS = {
    "curricumap_v0.1.0": HERE / "taxonomies" / "elt_yok_2018_v0.1.0.yaml",
    "curricumap_v0.2.0": "elt_yok_2018",
    "curricumap_lookup": LOOKUP,
    "curricumap_adapted": HERE / "taxonomies" / "elt_yok_2018_iuc_adapted.yaml",
}
LABELS = {"language_skills": "Language Skills", "pedagogy": "Pedagogy", "linguistics": "Linguistics",
          "literature": "Literature", "general_ed": "General Education"}


def write_lookup() -> None:
    """Overrides only, in source order: for the one title listed twice with different labels
    (Türk Eğitim Tarihi, 2018 MB and 2006 GK) the first, 2018, entry wins, as in v0.2.0."""
    spec = {"taxonomy": {
        "id": "elt_official_titles_lookup", "label": "ELT official titles as overrides (no rules)",
        "locale": {"language": "tr"},
        "domains": [{"id": d, "label": LABELS[d]} for d in DOMAINS],
        "rules": [],
        "overrides": [{"course": c["title"], "domain": c["domain"]} for c in source_courses()]}}
    header = "# Generated by validation/predict_rules.py from data/yok_programmes.csv; do not edit.\n"
    LOOKUP.write_text(header + yaml.safe_dump(spec, allow_unicode=True, sort_keys=False), "utf-8")


def main() -> None:
    write_lookup()
    titles = [c["title"] for c in target_courses()]
    for name, spec in SYSTEMS.items():
        if name == "curricumap_adapted" and not spec.exists():
            continue
        t0 = time.perf_counter()
        tax = load_taxonomy(spec)
        rows = []
        for title in titles:
            a = assign_domain(title, tax)
            rows.append({"title": title, "predicted": a.domain or ABSTAIN,
                         "detail": f"{a.method}:{a.pattern or ''}{':ambiguous' if a.ambiguous else ''}"})
        secs = time.perf_counter() - t0
        path = write_predictions(name, 1, rows)
        print(f"{name}: {sum(r['predicted'] != ABSTAIN for r in rows)}/{len(rows)} assigned "
              f"in {secs:.3f}s -> {path.name}")


if __name__ == "__main__":
    main()
