"""Write every validation number the paper quotes as LaTeX macros, so none is copied by hand.

Reads results/metrics_summary.csv, results/validation_facts.csv, results/keywords_only.csv,
results/effort.csv and the CurricuMap predictions; writes ../paper/generated/validation_numbers.tex
and copies the validation, effort and benchmark tables next to it.
"""
from __future__ import annotations

import math
import shutil

from common import RESULTS, read_csv

OUT = RESULTS.parent.parent / "paper" / "generated"

SYSTEMS = {  # metrics_summary system -> macro prefix
    "curricumap_v0.1.0": "vOne", "curricumap_v0.2.0": "vTwo", "curricumap_lookup": "look",
    "curricumap_adapted": "adapt",
    "string_1nn": "strNN", "charngram_lr": "chr", "e5_zeroshot": "eZS", "e5_1nn": "eNN",
    "gemma_zeroshot_greedy": "gmZSg", "gemma_zeroshot": "gmZS", "gemma_fewshot_greedy": "gmFSg",
    "gemma_fewshot": "gmFS", "claude_zeroshot": "clZS", "claude_fewshot": "clFS",
}
GIVEN_LIST = ("string_1nn", "charngram_lr", "e5_1nn", "gemma_fewshot_greedy", "gemma_fewshot",
              "claude_fewshot")  # the methods other than CurricuMap given the labelled official titles


WORDS = "zero one two three four five six seven eight nine".split()


def words(n) -> str:  # counts below ten are spelled out in running text
    n = int(n)
    return WORDS[n] if 0 <= n < 10 else str(n)


def pct(x) -> str:
    return f"{100 * float(x):.1f}"


def pval(p) -> str:
    p = float(p)
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"      # as in the validation table


def pval_text(p) -> str:
    p = float(p)
    return "$p<0.001$" if p < 0.001 else f"$p={p:.3f}$"


def bound(p, up: bool) -> str:  # p rounded outwards to three decimals, for "p <=" or "p >="
    p = round(float(p) * 1000, 6)
    return f"{max(math.ceil(p), 1) / 1000:.3f}" if up else f"{math.floor(p) / 1000:.3f}"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    facts = {r["fact"]: r["value"] for r in read_csv(RESULTS / "validation_facts.csv")}
    n = int(facts["n_titles"])
    lines = ["% Generated by validation/paper_numbers.py -- do not edit by hand.",
             f"\\newcommand{{\\nTitles}}{{{n}}}",
             f"\\newcommand{{\\nExact}}{{{facts['n_exact']}}}",
             f"\\newcommand{{\\nVariant}}{{{facts['n_variant']}}}",
             f"\\newcommand{{\\nUnseen}}{{{facts['n_unseen']}}}",
             f"\\newcommand{{\\nClusters}}{{{facts['n_clusters']}}}",
             f"\\newcommand{{\\clusterLo}}{{{pct(facts['cluster_wilson_lo_all_correct'])}}}",
             f"\\newcommand{{\\nVariantLoose}}{{{facts['n_variant_loose_lookup']}}}",
             f"\\newcommand{{\\nUnseenW}}{{{words(facts['n_unseen'])}}}",
             f"\\newcommand{{\\nVariantLooseW}}{{{words(facts['n_variant_loose_lookup'])}}}"]
    summary = {r["system"]: r for r in read_csv(RESULTS / "metrics_summary.csv")}
    for system, p in SYSTEMS.items():
        s = summary.get(system)
        if s is None:
            continue
        assigned, correct = round(float(s["coverage"]) * n), round(float(s["accuracy"]) * n)
        lines += [
            f"\\newcommand{{\\{p}Cov}}{{{pct(s['coverage'])}}}",
            f"\\newcommand{{\\{p}Acc}}{{{pct(s['accuracy'])}}}",
            f"\\newcommand{{\\{p}AccMin}}{{{pct(s['accuracy_min'])}}}",
            f"\\newcommand{{\\{p}AccMax}}{{{pct(s['accuracy_max'])}}}",
            f"\\newcommand{{\\{p}Kappa}}{{{float(s['kappa']):.3f}}}",
            f"\\newcommand{{\\{p}Off}}{{{pct(s['official_consistency'])}}}",
            f"\\newcommand{{\\{p}Correct}}{{{correct}}}",
            f"\\newcommand{{\\{p}Assigned}}{{{assigned}}}",
            f"\\newcommand{{\\{p}Flagged}}{{{n - assigned}}}",
            f"\\newcommand{{\\{p}Wrong}}{{{assigned - correct}}}",
            f"\\newcommand{{\\{p}Exact}}{{{s['correct_exact']}}}",
            f"\\newcommand{{\\{p}Variant}}{{{s['correct_variant']}}}",
            f"\\newcommand{{\\{p}Unseen}}{{{s['correct_unseen']}}}",
            f"\\newcommand{{\\{p}P}}{{{pval(s['mcnemar_p'])}}}",
            f"\\newcommand{{\\{p}Pt}}{{{pval_text(s['mcnemar_p'])}}}",
            f"\\newcommand{{\\{p}PMaxUp}}{{{bound(s['mcnemar_p_max'], up=True)}}}",
            f"\\newcommand{{\\{p}Identical}}{{{pct(s['identical_all_runs'])}}}",
            f"\\newcommand{{\\{p}Runs}}{{{s['n_runs']}}}",
            f"\\newcommand{{\\{p}RunsW}}{{{words(s['n_runs'])}}}",
            f"\\newcommand{{\\{p}WrongW}}{{{words(assigned - correct)}}}",
        ]
    given = [summary[s] for s in GIVEN_LIST if s in summary]
    if given:
        lines += [
            f"\\newcommand{{\\listAccMin}}{{{pct(min(float(r['accuracy_min']) for r in given))}}}",
            f"\\newcommand{{\\listAccMax}}{{{pct(max(float(r['accuracy_max']) for r in given))}}}",
            f"\\newcommand{{\\listPMin}}{{{bound(min(float(r['mcnemar_p_min']) for r in given), up=False)}}}"]
    rules = read_csv(RESULTS / "predictions" / "curricumap_v0.2.0__run1.csv")
    lines.append(f"\\newcommand{{\\nAmbiguous}}{{{sum(r['detail'].endswith(':ambiguous') for r in rules)}}}")
    kw = {r["fact"]: r["value"] for r in read_csv(RESULTS / "keywords_only.csv")}
    lines += [f"\\newcommand{{\\eltKwOnlyCorrect}}{{{kw['correct']}}}",
              f"\\newcommand{{\\eltKwOnlyEntries}}{{{kw['entries']}}}"]
    effort = {r["taxonomy"]: r for r in read_csv(RESULTS / "effort.csv")}
    for name, p in (("elt_yok_2018", "elt"), ("elt_yok_2018_iuc_adapted", "eltAdapt"),
                    ("elt_yok_2018_v0.1.0", "eltOld")):
        e = effort.get(name)
        if e:
            lines += [f"\\newcommand{{\\{p}{k.capitalize().replace('_', '')}}}{{{e[k]}}}"
                      for k in ("rules", "keywords", "regexes", "overrides", "yaml_lines")]
    (OUT / "validation_numbers.tex").write_text("\n".join(lines) + "\n", "utf-8")
    for t in ("table_validation.tex", "table_effort.tex"):
        if (RESULTS / t).exists():
            shutil.copy(RESULTS / t, OUT / t)
    bench = RESULTS.parent.parent / "benchmarks"
    for t in ("table_benchmark.tex", "benchmark_numbers.tex"):
        if (bench / t).exists():
            shutil.copy(bench / t, OUT / t)
    print(f"wrote {len(lines) - 1} macros to {OUT / 'validation_numbers.tex'}")


if __name__ == "__main__":
    main()
