"""Write the software numbers the paper quotes as LaTeX macros (paper/generated/software_numbers.tex):
the test count and statement coverage of the suite, and the share of missing course grades in the
illustrative example (Listing 2). The test count and coverage are also written into row C5 of
docs/code-metadata.md. Run from the repository root with the development environment:

    python paper/software_numbers.py
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "paper" / "generated" / "software_numbers.tex"
METADATA = REPO / "docs" / "code-metadata.md"


def test_stats() -> tuple[int, int]:
    run = subprocess.run([sys.executable, "-m", "pytest", "-o", "addopts=", "-q", "-p", "no:cacheprovider",
                          "--cov=curricumap", "--cov-report=term"], cwd=REPO, capture_output=True, text=True)
    if run.returncode != 0:
        sys.exit(run.stdout + run.stderr)
    passed = int(re.search(r"(\d+) passed", run.stdout).group(1))
    cover = int(re.search(r"^TOTAL\s+\d+\s+\d+\s+(\d+)%", run.stdout, flags=re.M).group(1))
    return passed, cover


def example() -> dict:
    """Run the paper's Listing 2 and return what Section 3.1 quotes."""
    import pandas as pd
    from curricumap.cli import main
    with tempfile.TemporaryDirectory() as tmp:
        data, out = Path(tmp) / "data", Path(tmp) / "out"
        main(["synth", "--taxonomy", "elt_yok_2018", "--out", str(data), "--n-students", "60", "--seed", "7"])
        main(["run", "--input", str(data / "transcript.csv"), "--taxonomy", "elt_yok_2018", "--out", str(out)])
        audit = json.loads((out / "audit.json").read_text("utf-8"))
        records = len(pd.read_csv(data / "transcript.csv"))
        courses = len(pd.read_csv(out / "provenance.csv"))
    doms = audit["domains"]
    return {"records": records, "courses": courses,
            "missing": [d["item_missing_pct"] for d in doms.values()],
            "alpha": {k: f"{d['alpha']:.3f}".lstrip("0") for k, d in doms.items()}}


def main() -> None:
    passed, cover = test_stats()
    ex = example()
    names = {"language_skills": "LS", "pedagogy": "Ped", "linguistics": "Ling", "literature": "Lit",
             "general_ed": "GE"}
    lines = ["% Generated by paper/software_numbers.py -- do not edit by hand.",
             f"\\newcommand{{\\nTests}}{{{passed}}}",
             f"\\newcommand{{\\covPct}}{{{cover}}}",
             f"\\newcommand{{\\exRecords}}{{{ex['records']}}}",
             f"\\newcommand{{\\exCourses}}{{{ex['courses']}}}",
             f"\\newcommand{{\\exMissMin}}{{{min(ex['missing']):.1f}}}",
             f"\\newcommand{{\\exMissMax}}{{{max(ex['missing']):.1f}}}",
             *[f"\\newcommand{{\\exAlpha{names[k]}}}{{{v}}}" for k, v in ex["alpha"].items()]]
    OUT.write_text("\n".join(lines) + "\n", "utf-8")
    md = METADATA.read_text("utf-8")
    METADATA.write_text(re.sub(r"\d+ tests, \d+% statement coverage",
                               f"{passed} tests, {cover}% statement coverage", md), "utf-8")
    print("\n".join(lines[1:]))


if __name__ == "__main__":
    main()
