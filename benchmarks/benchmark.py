"""Runtime and peak memory of `curricumap run` on synthetic transcripts of increasing size.

Each configuration is synthesised once, then `curricumap run` is executed REPS times in a
fresh Python process; the table reports the median wall time and the peak resident memory
of that process. Usage: python benchmarks/benchmark.py [--quick]
"""
from __future__ import annotations

import csv
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from curricumap import generate, load_taxonomy  # noqa: E402

HERE = Path(__file__).resolve().parent
CONFIGS = [(60, 3), (1_000, 3), (10_000, 3), (100_000, 3), (60, 30), (1_000, 30), (10_000, 30)]
REPS = 3


_PROBE = ("import resource, subprocess, sys, time\n"
          "t0 = time.perf_counter()\n"
          "subprocess.run(sys.argv[1:], check=True, capture_output=True)\n"
          "print(time.perf_counter() - t0, resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss)")


def run_once(transcript: Path, out: Path) -> tuple[float, float]:
    """Wall time (s) and peak resident memory (MB) of one `curricumap run` in a fresh process."""
    res = subprocess.run([sys.executable, "-c", _PROBE, sys.executable, "-m", "curricumap.cli", "run",
                          "--input", str(transcript), "--taxonomy", "elt_yok_2018", "--out", str(out)],
                         check=True, capture_output=True, text=True, cwd=HERE.parent / "src")
    secs, rss = res.stdout.split()
    return float(secs), int(rss) / (2**20 if sys.platform == "darwin" else 2**10)


def main(quick: bool = False) -> None:
    tax = load_taxonomy("elt_yok_2018")
    rows = []
    configs = CONFIGS[:2] if quick else CONFIGS
    with tempfile.TemporaryDirectory() as tmp:
        for n_students, cpd in configs:
            t0 = time.perf_counter()
            transcript, catalog = generate(tax, n_students=n_students, seed=1, courses_per_domain=cpd)
            synth_secs = time.perf_counter() - t0
            path = Path(tmp) / f"t_{n_students}_{cpd}.csv"
            transcript.to_csv(path, index=False)
            times, mems = [], []
            for rep in range(REPS):
                secs, mb = run_once(path, Path(tmp) / f"out_{rep}")
                times.append(secs)
                mems.append(mb)
            rows.append({"students": n_students, "courses": len(catalog), "records": len(transcript),
                         "synth_s": round(synth_secs, 2), "run_s_median": round(statistics.median(times), 2),
                         "run_s_min": round(min(times), 2), "run_s_max": round(max(times), 2),
                         "peak_rss_mb": round(max(mems), 1)})
            print(rows[-1], flush=True)
    env = {"python": platform.python_version(), "pandas": pd.__version__, "numpy": np.__version__,
           "machine": platform.machine(), "os": f"{platform.system()} {platform.release()}",
           "processor": platform.processor() or "unknown"}
    out = HERE / "results.csv"
    with open(out, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (HERE / "environment.txt").write_text("\n".join(f"{k}: {v}" for k, v in env.items()) + "\n", "utf-8")
    lines = [r"\begin{tabular}{@{}rrrrr@{}}", r"\toprule",
             r"Students & Courses & Grade records & Run time (s) & Peak memory (MB) \\", r"\midrule"]
    for r in rows:
        lines.append(f"{r['students']:,} & {r['courses']} & {r['records']:,} & {r['run_s_median']:.2f} & "
                     f"{r['peak_rss_mb']:.0f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (HERE / "table_benchmark.tex").write_text("\n".join(lines).replace(",", "{,}") + "\n", "utf-8")
    big = max(rows, key=lambda r: r["records"])
    small = min(rows, key=lambda r: r["records"])
    macros = {"benchMaxRecords": f"{big['records'] / 1e6:.1f}", "benchMaxStudents": f"{big['students']:,}".replace(",", "{,}"),
              "benchMaxTime": f"{big['run_s_median']:.2f}", "benchMaxMem": f"{big['peak_rss_mb']:.0f}",
              "benchStartup": f"{small['run_s_median']:.1f}"}
    (HERE / "benchmark_numbers.tex").write_text(
        "% Generated by benchmarks/benchmark.py -- do not edit by hand.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()), "utf-8")
    print(env)


if __name__ == "__main__":
    main(quick="--quick" in sys.argv)
